/** Small deterministic hash -> [0, 1). */
const rnd = (v, k) => { const s = Math.sin(v * 127.1 + k * 311.7) * 43758.5453; return s - Math.floor(s); };

/** Local rects [cx, cz, w, d] of a site turned by ry about (x, z) -> world AABBs (same convention as src/farmSites.js orientedSolids). */
function solids(site, rects) {
  const c = Math.cos(site.ry), s = Math.sin(site.ry);
  return rects.map(([cx, cz, w, d]) => {
    const wx = site.x + cx * c + cz * s, wz = site.z - cx * s + cz * c;
    const hx = (Math.abs(c) * w + Math.abs(s) * d) / 2, hz = (Math.abs(s) * w + Math.abs(c) * d) / 2;
    return { minX: wx - hx, maxX: wx + hx, minZ: wz - hz, maxZ: wz + hz };
  });
}

/** Local point -> world (for the herd, whose placements are world-space). */
function toWorld(site, lx, lz) {
  const c = Math.cos(site.ry), s = Math.sin(site.ry);
  return { x: site.x + lx * c + lz * s, z: site.z - lx * s + lz * c };
}

// straw tones as multipliers on the haystack models' own baked colour (src/haystacks.js hayPlacements does the same sums)
const STRAW = [0xcdcbd7, 0xdbd9e9, 0xbcbabd, 0xd6d6de];
const DUNG = [0xd8cfc0, 0xc8bfae, 0xcfc4b0];
const HAY_ORDER = [['cone', 'half'], ['heap', 'cone'], ['half', 'heap']];

/** Builds one site: returns a Group, or { group, onFrame } when it holds animals. */
export function buildLongWalkSite(site, name) {
  const v = site.v;
  const group = new THREE.Group();
  group.name = name;
  const carrier = new THREE.Mesh(new THREE.BufferGeometry(), new THREE.MeshBasicMaterial());
  carrier.name = `${name}_solids`;
  carrier.visible = false;
  group.add(carrier);
  const local = new THREE.Group(); // the site's own frame: origin on the ground, +z toward the road
  local.position.set(site.x, 0, site.z);
  local.rotation.y = site.ry;
  group.add(local);
  let rects = [];
  let onFrame = null;
  const jit = (k, a) => (rnd(v, k) - 0.5) * 2 * a;

  if (site.kind === 'well') {
    // the village well, its spout side turned along the road (never toward it)
    addFieldProps(local, [{ part: 'well', x: 0, z: 0, ry: (rnd(v, 1) < 0.5 ? 0 : Math.PI) + jit(2, 0.15) }], `${name}_well`);
    rects = [[0, 0, 4.4, 4.4]]; // no pots here: two more draw calls, and the east-side viewpoints already sit at the 150 ceiling
  } else if (site.kind === 'shrine') {
    // a small roadside shrine, its front to the road, turned a few degrees off square like a real one
    addFieldProps(local, [{ part: 'field_shrine', x: 0, z: 0, ry: jit(1, 0.12) }], `${name}_shrine`);
    rects = [[0.1, -0.15, 3.8, 3.4]];
  } else if (site.kind === 'gate') {
    // a pair of field-gate piers set back from the road, leaves swung open away from it (the map's boundary gates)
    const gap = 1.8 + 0.3 * rnd(v, 1);
    addFieldProps(local, [
      { part: 'field_gate', x: -gap, z: 1.4, ry: Math.PI + jit(2, 0.05) },
      { part: 'field_gate_b', x: gap, z: 1.4, ry: Math.PI + jit(3, 0.05) },
    ], `${name}_gate`);
    rects = [[-gap, 1.4, 0.95, 0.95], [gap, 1.4, 0.95, 0.95]];
  } else if (site.kind === 'hay') {
    // two stacks of different shape and size, a gobar stack beside them
    const [t0, t1] = HAY_ORDER[v % 3];
    const s0 = 0.5 + 0.12 * rnd(v, 1), s1 = 0.36 + 0.1 * rnd(v, 2);
    const p0 = [-1.0 + jit(3, 0.3), -0.5], p1 = [1.55 + jit(4, 0.25), 0.55 + jit(5, 0.3)];
    addHaystacks(local, [
      { type: t0, x: p0[0], z: p0[1], ry: rnd(v, 6) * 6.28, s: s0, tint: STRAW[v % 4] },
      { type: t1, x: p1[0], z: p1[1], ry: rnd(v, 7) * 6.28, s: s1, tint: STRAW[(v + 1) % 4] },
    ], `${name}_hay`);
    const g = [0.3 + jit(8, 0.4), 2.05];
    addGobar(local, [{ type: rnd(v, 9) < 0.5 ? 'stack' : 'stack_b', x: g[0], z: g[1], ry: rnd(v, 10) * 6.28, s: 0.75 + 0.2 * rnd(v, 11), tint: DUNG[v % 3] }], `${name}_gobar`);
    rects = [[p0[0], p0[1], 4.2 * s0, 4.2 * s0], [p1[0], p1[1], 4.2 * s1, 4.2 * s1], [g[0], g[1], 1.3, 1.3]];
  } else if (site.kind === 'buffalo') {
    // a buffalo (or a cow and a buffalo) standing by a small fodder heap; the herd is one instanced, textured mesh
    const two = rnd(v, 1) < 0.6;
    const a = toWorld(site, -0.9, 0.2), b = toWorld(site, 1.25, 0.75);
    const herd = createCattleHerd([
      { x: a.x, z: a.z, rotationY: site.ry + Math.PI / 2 + jit(2, 0.5), buffalo: true },
      ...(two ? [{ x: b.x, z: b.z, rotationY: site.ry - Math.PI / 2 + jit(3, 0.6), buffalo: rnd(v, 4) < 0.5 }] : []),
    ]);
    group.add(herd.mesh);
    onFrame = (dt) => herd.update(dt);
    const hs = 0.26 + 0.06 * rnd(v, 5);
    addHaystacks(local, [{ type: 'heap', x: 0.2 + jit(6, 0.3), z: -1.65, ry: rnd(v, 7) * 6.28, s: hs, tint: STRAW[v % 4] }], `${name}_fodder`);
    rects = [[0.2, -1.65, 2.6 * hs * 2, 2.0 * hs * 2]];
  } else if (site.kind === 'pump') {
    // a hand pump on its plinth, a steel ghada under the spout and a matka beside it; the pump model varies per site
    const sink = new Map();
    const type = ['mark2', 'old', 'cracked'][v % 3];
    Promise.all([
      addHandPumps(local, [{ type, x: 0, z: 0, ry: Math.PI / 2 * (v % 4) + jit(1, 0.2), s: 0.9 + 0.1 * rnd(v, 2), tint: 0xffffff }], `${name}_pump`, sink),
      addPots(local, [
        { type: 'ghada', x: 0.75 + jit(3, 0.1), z: 0.55, ry: rnd(v, 4) * 6.28, s: 0.9, tint: 0xe6e2da },
        { type: rnd(v, 5) < 0.5 ? 'matka' : 'surahi', x: -0.85, z: 0.35 + jit(6, 0.2), ry: rnd(v, 7) * 6.28, s: 0.85 + 0.1 * rnd(v, 8), lean: 0.05, tint: 0xeee0d2 },
      ], `${name}_pots`, sink),
    ]).then(() => flushMerged(local, sink, `${name}_props`, false));
    rects = [[0, 0, 0.8, 0.8], [0.75, 0.55, 0.5, 0.5], [-0.85, 0.35, 0.55, 0.55]];
  }
  carrier.userData.colliderBoxes = solids(site, rects);
  return onFrame ? { group, onFrame } : group;
}

/** One zone per site. Called once from src/main.js with the zone manager. */
export function registerLongWalks(zoneManager) {
  LONG_WALK_SITES.forEach((site, i) => {
    const name = `long_walk_${i}_${site.kind}`;
    zoneManager.register(name, { x: site.x, z: site.z, buildRadius: 60, teardownRadius: 80, detail: true, visibleRadius: 75, build: () => buildLongWalkSite(site, name) });
  });
}
