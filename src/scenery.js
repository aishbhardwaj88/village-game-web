const yawOf = (p) => (p.ry !== undefined ? p.ry : (p.q * Math.PI) / 2);
/** Local (x along the row, z toward the lane) -> world, for any yaw (same convention as three.js rotation.y). */
function rowPt(p, lx, lz) {
  const th = yawOf(p), c = Math.cos(th), s = Math.sin(th);
  return { x: p.x + lx * c + lz * s, z: p.z - lx * s + lz * c };
}
/** A doorstep in front of row i (for jobs): `door` is the point on the lane, `stand` 1.4 m in front of the house face, `ry` faces out. */
export function abadiDoorstep(i, along = 0) {
  const p = PLACEMENTS[i];
  return { door: rowPt(p, along, 6.0), stand: rowPt(p, along, 4.9), ry: yawOf(p) };
}
