/** Local rects [cx, cz, w, d] of a site turned by ry about (x, z) -> world AABBs (same convention as src/longWalks.js). */
function solids(site, rects) {
  const c = Math.cos(site.ry), s = Math.sin(site.ry);
  return rects.map(([cx, cz, w, d]) => {
    const wx = site.x + cx * c + cz * s, wz = site.z - cx * s + cz * c;
    const hx = (Math.abs(c) * w + Math.abs(s) * d) / 2, hz = (Math.abs(s) * w + Math.abs(c) * d) / 2;
    return { minX: wx - hx, maxX: wx + hx, minZ: wz - hz, maxZ: wz + hz };
  });
}

const PEOPLE_GEO = new THREE.CapsuleGeometry(0.3, 1.1, 3, 8);
let PEOPLE_MAT = null;

/** Builds one site: a Group holding the model frame (`local`), the world-baked code parts and the people. */
export function buildRideNook(site, name) {
  const v = site.v;
  const group = new THREE.Group();
  group.name = name;
  const carrier = new THREE.Mesh(new THREE.BufferGeometry(), new THREE.MeshBasicMaterial());
  carrier.name = `${name}_solids`;
  carrier.visible = false;
  group.add(carrier);
  const local = new THREE.Group(); // models, in the site's own frame: origin on the ground, +z toward the road
  local.position.set(site.x, 0, site.z);
  local.rotation.y = site.ry;
  group.add(local);
  const P = new Parts();
  const people = []; // [lx, y, lz, yaw, sx, sy, lying]
  const jit = (k, a) => (rnd(v, k) - 0.5) * 2 * a;
  const flip = rnd(v, 99) < 0.5 ? -1 : 1; // mirror the layout along the road
  const sink = new Map();
  const loads = [];
  let rects = [];

  if (site.kind === 'rest') {
    const cx = 0.1 * flip, cz = -0.25, cy = jit(1, 0.2);
    charpai(P, cx, cz, cy, v, 2);
    const napping = rnd(v, 3) < 0.55;
    if (napping) people.push([cx + jit(4, 0.15), 0.42 + 0.27, cz, cy, 1.0, 0.72, true]); // dopahar nap, along the bed
    else people.push([cx + 0.55 * flip, 0.36, cz + 0.42, Math.PI + jit(5, 0.4), 1.12, 0.58, false]); // sitting on the edge, facing the road
    // chappals under the bed, a folded towel on the rail
    P.box('wood', 0.1, 0.02, 0.26, cx + 0.3, 0.01, cz + 0.62, 0x4a3828, 0.3);
    P.box('wood', 0.1, 0.02, 0.26, cx + 0.46, 0.01, cz + 0.6, 0x4a3828, -0.2);
    P.box('jute', 0.34, 0.03, 0.12, cx - 0.7 * flip, 0.43, cz - 0.43, pick([0xc8c0b0, 0xb07060, 0x8a9ab0], v, 6), cy);
    // matka with a kulhad on its mouth, a steel lota, a hurricane lantern at the head
    const mx = cx - 1.35 * flip, mz = cz + 0.35;
    loads.push(addPots(local, [
      { type: 'matka', x: mx, z: mz, ry: rnd(v, 7) * 6.28, s: 0.85 + 0.1 * rnd(v, 8), lean: 0.02, tint: 0xeee0d2 },
      { type: 'kulhad', x: mx + 0.32 * flip, z: mz + 0.18, ry: rnd(v, 9) * 6.28, s: 1.0, lean: 0.03, tint: 0xe6d6c4 },
      ...(rnd(v, 10) < 0.6 ? [{ type: 'ghada', x: cx + 1.2 * flip, z: cz + 0.55, ry: rnd(v, 11) * 6.28, s: 0.7, tint: 0xe6e2da }] : []),
    ], `${name}_pots`, sink));
    loads.push(addLanterns(local, [{ type: rnd(v, 12) < 0.6 ? 'hurricane' : 'tin', x: mx - 0.05, y: 0, z: mz - 0.55, ry: rnd(v, 13) * 6.28, s: 1.0, tint: 0xffffff }], `${name}_lantern`, sink));
    // a cycle parked behind the bed, along the road
    const bx = -0.3 * flip, bz = -1.55;
    if (rnd(v, 14) < 0.75) { cycle(P, bx, bz, (flip > 0 ? 0 : Math.PI) + jit(15, 0.15), v, 16); rects.push([bx, bz, 1.7, 0.6]); }
    rects.push([cx, cz, 2.1, 1.15], [mx, mz, 0.6, 0.6]);
  } else if (site.kind === 'dung') {
    // a short brick wall, plaster capped, the cakes slapped on its road face to dry
    const wl = 2.0 + 0.4 * rnd(v, 1), wh = 1.45 + 0.15 * rnd(v, 2), wz = -0.9, wy = jit(3, 0.08);
    const bt = pick(BRICK, v, 4);
    P.box('brick', wl, wh, 0.23, 0, wh / 2, wz, bt, wy, 0, 0, 1.2);
    P.box('plaster', wl + 0.06, 0.07, 0.29, 0, wh + 0.035, wz, 0xc8bca8, wy, 0, 0, 0.5);
    loads.push(addGobar(local, [
      { type: rnd(v, 5) < 0.5 ? 'wall' : 'wall_b', x: -0.15 * flip, z: wz + 0.12, ry: wy, s: 1.0, tint: pick(DUNG, v, 6) },
      ...(wl > 2.2 ? [{ type: rnd(v, 7) < 0.5 ? 'wall' : 'wall_b', x: 0.75 * flip, z: wz + 0.12, ry: wy, s: 0.8, tint: pick(DUNG, v, 8) }] : []),
      { type: rnd(v, 9) < 0.5 ? 'stack' : 'stack_b', x: (wl / 2 + 0.75) * flip, z: -0.5, ry: rnd(v, 10) * 6.28, s: 0.75 + 0.2 * rnd(v, 11), tint: pick(DUNG, v, 12) },
    ], `${name}_gobar`));
    // she crouches at the wall, her tasla (shallow iron pan) beside her
    const px = 0.35 * flip, pz = -0.2;
    if (rnd(v, 13) < 0.8) people.push([px, 0, pz, jit(14, 0.3), 1.15, 0.52, false]);
    const tx = px + 0.55 * flip, tz = pz + 0.2;
    P.box('metal', 0.5, 0.06, 0.5, tx, 0.05, tz, 0x5a5550, rnd(v, 15) * 3);
    P.box('metal', 0.4, 0.02, 0.4, tx, 0.085, tz, 0x4a4038, rnd(v, 15) * 3);
    rects.push([0, wz, wl, 0.3], [(wl / 2 + 0.75) * flip, -0.5, 1.4, 1.4], [px, pz, 0.6, 0.6]);
  } else if (site.kind === 'pump') {
    const type = ['mark2', 'old', 'cracked'][v % 3];
    const py = Math.PI / 2 * (rnd(v, 1) < 0.5 ? 1 : -1) + jit(2, 0.15); // the drain runs along the road, not into it
    loads.push(addHandPumps(local, [{ type, x: 0, z: -0.4, ry: py, s: 0.9 + 0.1 * rnd(v, 3), tint: 0xffffff }], `${name}_pump`, sink));
    loads.push(addPots(local, [
      { type: 'ghada', x: 0.45, z: 0.35, ry: rnd(v, 4) * 6.28, s: 0.9, tint: 0xe6e2da },
      { type: rnd(v, 5) < 0.5 ? 'matka' : 'surahi', x: -0.65, z: 0.45 + jit(6, 0.15), ry: rnd(v, 7) * 6.28, s: 0.85 + 0.1 * rnd(v, 8), lean: 0.05, tint: 0xeee0d2 },
    ], `${name}_pots`, sink));
    const bx = 0.2 * flip, bz = -1.75;
    cycle(P, bx, bz, (flip > 0 ? 0 : Math.PI) + jit(9, 0.2), v, 10);
    if (rnd(v, 11) < 0.6) people.push([-0.75 * flip, 0, 1.0, Math.PI + jit(12, 0.5), 0.75, 0.72, false]); // a child waiting his turn
    rects.push([0, -0.4, 0.8, 0.8], [0.45, 0.35, 0.5, 0.5], [-0.65, 0.45, 0.55, 0.55], [bx, bz, 1.7, 0.6]);
  } else if (site.kind === 'hay') {
    const big = 0.42 + 0.1 * rnd(v, 1), small = 0.28 + 0.08 * rnd(v, 2);
    const p0 = [-0.6 * flip, -0.9], p1 = [1.6 * flip, 0.0 + jit(3, 0.3)];
    loads.push(addHaystacks(local, [
      { type: pick(['heap', 'cone'], v, 4), x: p0[0], z: p0[1], ry: rnd(v, 5) * 6.28, s: big, tint: pick(STRAW, v, 6) },
      { type: pick(['half', 'cone', 'heap'], v, 7), x: p1[0], z: p1[1], ry: rnd(v, 8) * 6.28, s: small, tint: pick(STRAW, v, 9) },
    ], `${name}_hay`));
    const g = [-1.9 * flip, 0.3];
    loads.push(addGobar(local, [{ type: rnd(v, 10) < 0.5 ? 'stack' : 'stack_b', x: g[0], z: g[1], ry: rnd(v, 11) * 6.28, s: 0.7 + 0.2 * rnd(v, 12), tint: pick(DUNG, v, 13) }], `${name}_gobar`));
    // leaned on the big stack's road side: a cycle, or a charpai stood on its long edge
    if (rnd(v, 14) < 0.5) cycle(P, p0[0] + 0.2 * flip, p0[1] + 1.55 * big + 0.15, jit(15, 0.2) + (flip > 0 ? 0 : Math.PI), v, 16, -0.22);
    else {
      const b = M(p0[0] - 0.2 * flip, 0, p0[1] + 1.5 * big + 0.2, 0, jit(17, 0.15)).multiply(M(0, 0.48, 0, -1.25, 0, 0)).multiply(M(0, -0.21, 0));
      const tmp = new Parts();
      charpai(tmp, 0, 0, 0, v, 18);
      for (const [mat, list] of Object.entries(tmp.by)) for (const geo of list) P.push(mat, geo, b);
    }
    rects.push([p0[0], p0[1], 3.6 * big, 3.0 * big], [p1[0], p1[1], 3.4 * small, 3.0 * small], [g[0], g[1], 1.2, 1.2], [p0[0], p0[1] + 1.5 * big + 0.2, 1.9, 0.5]);
  } else if (site.kind === 'laundry') {
    const ly = jit(1, 0.12);
    loads.push(addLaundryLine(local, { x: 0, z: -1.2, ry: ly, seed: v, name: `${name}_line` }));
    const cx = 0.7 * flip, cz = 0.55, cy = jit(2, 0.35);
    charpai(P, cx, cz, cy, v, 3);
    // a folded quilt and a pillow on the bed; she sits at the foot, folding
    P.box('jute', 0.7, 0.12, 0.55, cx - 0.45 * flip, 0.5, cz, pick([0x9a4a4a, 0x6a6a9a, 0xb08a5a], v, 4), cy + 0.1, 0, 0, 0.5);
    P.box('jute', 0.45, 0.08, 0.3, cx - 0.5 * flip, 0.6, cz - 0.05, 0xd8d0c0, cy - 0.15, 0, 0, 0.5);
    if (rnd(v, 5) < 0.8) people.push([cx + 0.55 * flip, 0.36, cz + 0.4, Math.PI + jit(6, 0.5), 1.12, 0.58, false]);
    loads.push(addPots(local, [{ type: 'ghada', x: -1.9 * flip, z: 0.3, ry: rnd(v, 7) * 6.28, s: 0.85, tint: 0xe6e2da }], `${name}_pots`, sink));
    const c = Math.cos(ly), s = Math.sin(ly);
    for (const e of [-2.75, 2.75]) rects.push([e * c, -1.2 - e * s, 0.3, 0.3]); // the two posts (the line itself rides in the cloth mesh, soft by rule)
    rects.push([cx, cz, 2.1, 1.15], [-1.9 * flip, 0.3, 0.5, 0.5]);
  } else if (site.kind === 'well') {
    loads.push(addFieldProps(local, [{ part: 'well', x: 0, z: -0.6, ry: (rnd(v, 1) < 0.5 ? 0 : Math.PI) + jit(2, 0.15) }], `${name}_well`));
    loads.push(addPots(local, [
      { type: 'ghada', x: 1.9 * flip, z: 1.2, ry: rnd(v, 3) * 6.28, s: 0.9, tint: 0xe6e2da },
      { type: 'ghada', x: 2.2 * flip, z: 1.45, ry: rnd(v, 4) * 6.28, s: 0.75, tint: 0xd8d4cc },
      { type: rnd(v, 5) < 0.5 ? 'matka' : 'surahi', x: -2.1 * flip, z: 1.3, ry: rnd(v, 6) * 6.28, s: 0.85, lean: 0.04, tint: 0xeee0d2 },
    ], `${name}_pots`, sink));
    if (rnd(v, 7) < 0.75) people.push([1.4 * flip, 0, 1.6, Math.PI * 0.75 * flip + jit(8, 0.3), 1.0, 0.95, false]);
    rects.push([0, -0.6, 4.4, 4.4], [2.05 * flip, 1.32, 0.8, 0.7], [-2.1 * flip, 1.3, 0.55, 0.55]);
  }
  for (const p of people) rects.push(p[6] ? [p[0], p[2], 0.1, 0.1] : [p[0], p[2], 0.62, 0.62]);
  carrier.userData.colliderBoxes = solids(site, rects);

  // models: merged per material in the local frame, then drawn through the shared batches
  Promise.all(loads).then(() => { if (sink.size) flushMerged(local, sink, `${name}_props`, false); });
  batchPlaceModelWhenRooted(local, name, true);

  // code parts: one world-baked mesh per material, drawn through the shared tiled batches
  const world = M(site.x, 0, site.z, 0, site.ry);
  const code = new THREE.Group();
  code.name = `${name}_built`;
  for (const [mat, list] of Object.entries(P.by)) {
    const geo = mergeGeometries(list.map((g) => g.clone().applyMatrix4(world)));
    if (!geo) continue;
    const mesh = new THREE.Mesh(geo, getTiledMaterial(mat, { repeatX: 1, repeatY: 1, roughness: 1, vertexColors: true }));
    mesh.name = `${name}_${mat}`;
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    code.add(mesh);
  }
  group.add(code);
  batchLateGroup(code, `${name}_built`);

  // people: capsule placeholders (same style as src/lifeScenes.js), one small InstancedMesh, in their own sub-group
  if (people.length) {
    PEOPLE_MAT ||= new THREE.MeshStandardMaterial({ roughness: 0.85 });
    const pg = new THREE.Group();
    pg.name = `${name}_people`;
    const mesh = new THREE.InstancedMesh(PEOPLE_GEO, PEOPLE_MAT, people.length);
    mesh.name = `${name}_people_capsules`;
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    const col = new THREE.Color(), m4 = new THREE.Matrix4();
    people.forEach(([lx, y, lz, yaw, sx, sy, lying], i) => {
      const h = 1.7 * sy;
      const lm = lying
        ? M(lx, y, lz, 0, yaw, Math.PI / 2, new THREE.Vector3(sx * 0.95, sy * 1.25, sx * 0.95)) // on its side along the charpai: capsule axis along local x
        : M(lx, y + h / 2, lz, 0, yaw, 0, new THREE.Vector3(sx, sy, sx));
      mesh.setMatrixAt(i, m4.multiplyMatrices(world, lm));
      mesh.setColorAt(i, col.setHex(pick(CLOTHES, v, 40 + i)));
    });
    mesh.instanceMatrix.needsUpdate = true;
    if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true;
    mesh.computeBoundingSphere();
    pg.add(mesh); batchPeopleMesh(mesh);
    group.add(pg);
  }
  return group;
}

/** One zone per site. Called once from src/main.js with the zone manager. */
export function registerRideNooks(zoneManager) {
  RIDE_NOOK_SITES.forEach((site, i) => {
    if (!KINDS.includes(site.kind)) return;
    const name = `ride_nook_${i}_${site.kind}`;
    zoneManager.register(name, { x: site.x, z: site.z, buildRadius: 60, teardownRadius: 80, detail: true, visibleRadius: 75, build: () => buildRideNook(site, name) });
  });
}
