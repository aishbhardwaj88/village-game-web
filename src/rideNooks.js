// code-built parts, collected per material in the SITE's local metres, baked to world space at the end
class Parts {
  constructor() { this.by = {}; }
  push(mat, geo, m4) {
    let g = geo.index ? geo.toNonIndexed() : geo;
    for (const k of Object.keys(g.attributes)) if (!['position', 'normal', 'uv', 'color'].includes(k)) g.deleteAttribute(k);
    if (m4) g.applyMatrix4(m4);
    (this.by[mat] ||= []).push(g);
  }
  /** A textured box: size w h d, centre x y z, turned (rx, ry, rz). */
  box(mat, w, h, d, x, y, z, tint, ry = 0, rx = 0, rz = 0, tileSize = 1.0) {
    const m = texturedBox(w, h, d, mat, { tileSize, tint, tintStrength: 0.6 });
    this.push(mat, m.geometry, M(x, y, z, rx, ry, rz));
  }
  /** A round tube from (x0,y0) to (x1,y1) in the plane z (local), radius r. */
  tube(mat, x0, y0, x1, y1, z, r, tint, base) {
    const L = Math.hypot(x1 - x0, y1 - y0);
    const g = new THREE.CylinderGeometry(r, r, L, 5, 1, true);
    uvMetres(g, 1.0);
    bakeFlatTintColors(g, tint, 0.7);
    this.push(mat, g, M((x0 + x1) / 2, (y0 + y1) / 2, z, 0, 0, Math.atan2(y1 - y0, x1 - x0) - Math.PI / 2).premultiply(base));
  }
  torus(mat, R, r, x, y, z, tint, base, seg = 16) {
    const g = new THREE.TorusGeometry(R, r, 4, seg);
    uvMetres(g, 1.0);
    bakeFlatTintColors(g, tint, 0.7);
    this.push(mat, g, M(x, y, z).premultiply(base));
  }
}
const _q = new THREE.Quaternion(), _e = new THREE.Euler(), ONE = new THREE.Vector3(1, 1, 1);
function M(x, y, z, rx = 0, ry = 0, rz = 0, s = null) {
  return new THREE.Matrix4().compose(new THREE.Vector3(x, y, z), _q.setFromEuler(_e.set(rx, ry, rz, 'YXZ')), s || ONE);
}
/** Scales a primitive's 0..1 UVs to roughly its size in metres (the library's tile is 1 m for wood/metal). */
function uvMetres(g, tile) {
  g.computeBoundingBox();
  const b = g.boundingBox, span = Math.max(b.max.x - b.min.x, b.max.y - b.min.y, b.max.z - b.min.z) / tile;
  const uv = g.attributes.uv;
  for (let i = 0; i < uv.count; i++) uv.setXY(i, uv.getX(i) * span, uv.getY(i) * span * 0.25);
}

/** A charpai: four legs, side and end rails, the rope bed MODELLED as crossing strips, sagging a little in the middle.
 *  Long axis along local x. `on` = stood on its side (leaned against something), else on its legs. */
function charpai(P, x, z, ry, v, k, { L = 1.9, W = 0.95, H = 0.42 } = {}) {
  const fr = pick(FRAME, v, k), rope = pick(ROPE, v, k + 1);
  const base = M(x, 0, z, 0, ry);
  const b = (mat, w, h, d, bx, by, bz, t, ty = 0) => {
    const m = texturedBox(w, h, d, mat, { tileSize: 1.0, tint: t, tintStrength: 0.6 });
    P.push(mat, m.geometry, M(bx, by, bz, 0, ty).premultiply(base));
  };
  for (const [sx, sz] of [[-1, -1], [1, -1], [-1, 1], [1, 1]]) b('wood', 0.075, H, 0.075, sx * (L / 2 - 0.05), H / 2, sz * (W / 2 - 0.05), fr);
  for (const s of [-1, 1]) {
    b('wood', L, 0.065, 0.06, 0, H - 0.02, s * (W / 2 - 0.05), fr);
    b('wood', 0.06, 0.065, W - 0.1, s * (L / 2 - 0.05), H - 0.02, 0, fr);
  }
  // the weave: strips both ways, alternating a few mm up and down so the crossings read; the middle sags ~3 cm
  const nx = 7, nz = 15, sag = 0.03;
  const yAt = (u) => H - 0.01 - sag * (1 - u * u);
  for (let i = 0; i < nx; i++) {
    const zz = -W / 2 + 0.12 + (i * (W - 0.24)) / (nx - 1);
    b('jute', L - 0.16, 0.014, 0.05, 0, yAt(zz / (W / 2)) + (i % 2 ? 0.004 : -0.004), zz, rope);
  }
  for (let i = 0; i < nz; i++) {
    const xx = -L / 2 + 0.12 + (i * (L - 0.24)) / (nz - 1);
    b('jute', 0.05, 0.014, W - 0.16, xx, yAt(xx / (L / 2)) + (i % 2 ? -0.004 : 0.004), 0, rope);
  }
  return base;
}

/** A bicycle, front toward local +x, parked on its side stand (leaning a few degrees), or leaned (lean > 0) against something. */
function cycle(P, x, z, ry, v, k, lean = 0.09) {
  const c = pick(CYCLE, v, k), dark = 0x1e1e20, steel = 0x9a9ea2;
  const base = M(x, 0, z, lean, ry, 0); // YXZ: yaw first, then the lean about the bike's own long axis
  const R = 0.35, fx = 0.53, rx = -0.53;
  for (const wx of [rx, fx]) {
    P.torus('metal', R - 0.02, 0.022, wx, R, 0, dark, base, 18); // tyre
    P.torus('metal', R - 0.06, 0.008, wx, R, 0, steel, base, 14); // rim
    for (let s = 0; s < 6; s++) { const a = (s / 6) * Math.PI; P.tube('metal', wx - Math.cos(a) * (R - 0.06), R - Math.sin(a) * (R - 0.06), wx + Math.cos(a) * (R - 0.06), R + Math.sin(a) * (R - 0.06), 0, 0.003, steel, base); }
  }
  const bb = [0.0, 0.3], seat = [-0.2, 0.86], head = [0.42, 0.82];
  P.tube('metal', bb[0], bb[1], seat[0], seat[1], 0, 0.018, c, base); // seat tube
  P.tube('metal', bb[0], bb[1], head[0], head[1] - 0.06, 0, 0.02, c, base); // down tube
  P.tube('metal', seat[0], seat[1] - 0.04, head[0], head[1], 0, 0.018, c, base); // top tube (roadster: level)
  for (const s of [-0.04, 0.04]) {
    P.tube('metal', bb[0], bb[1], rx, R, s, 0.011, c, base); // chain stays
    P.tube('metal', seat[0], seat[1] - 0.05, rx, R, s, 0.01, c, base); // seat stays
    P.tube('metal', head[0], head[1], fx, R, s, 0.012, c, base); // fork
  }
  P.tube('metal', head[0], head[1], head[0] - 0.02, head[1] + 0.16, 0, 0.014, steel, base); // stem
  const hb = new THREE.CylinderGeometry(0.012, 0.012, 0.56, 5, 1, true); uvMetres(hb, 1); bakeFlatTintColors(hb, steel, 0.7);
  P.push('metal', hb, M(head[0] - 0.05, head[1] + 0.16, 0, Math.PI / 2, 0, 0).premultiply(base)); // handlebar across
  for (const s of [-0.27, 0.27]) P.push('metal', texturedBox(0.03, 0.03, 0.1, 'metal', { tileSize: 1, tint: dark, tintStrength: 0.8 }).geometry, M(head[0] - 0.08, head[1] + 0.16, s).premultiply(base)); // grips
  P.push('metal', texturedBox(0.26, 0.06, 0.13, 'metal', { tileSize: 1, tint: dark, tintStrength: 0.8 }).geometry, M(seat[0] - 0.02, seat[1] + 0.06, 0).premultiply(base)); // saddle
  P.push('metal', texturedBox(0.42, 0.02, 0.16, 'metal', { tileSize: 1, tint: steel, tintStrength: 0.5 }).geometry, M(rx + 0.03, R + 0.3, 0).premultiply(base)); // carrier
  P.push('metal', texturedBox(0.06, 0.02, 0.22, 'metal', { tileSize: 1, tint: steel, tintStrength: 0.5 }).geometry, M(fx - 0.02, R + 0.33, 0).premultiply(base)); // front mudguard lip
  P.push('metal', texturedBox(0.2, 0.012, 0.06, 'metal', { tileSize: 1, tint: c, tintStrength: 0.7 }).geometry, M(0.02, 0.3, 0.09).premultiply(base)); // chain guard
  P.push('metal', texturedBox(0.16, 0.03, 0.08, 'metal', { tileSize: 1, tint: dark, tintStrength: 0.8 }).geometry, M(0.02, 0.3, -0.09).premultiply(base)); // pedal
}

