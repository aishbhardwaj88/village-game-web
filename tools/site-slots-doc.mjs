#!/usr/bin/env node
/**
 * Regenerates the "Building slots" tables in docs/asset-slots.md from the live game, so the published target
 * dimensions, front direction and door position are the real ones, not typed by hand.
 *
 * It builds every streamed place (src/siteSlots.js reads each placeholder's own bounding box and doors), reads the hero
 * slots out of the asset-slot registry, and rewrites the block between the SITE-SLOTS markers in docs/asset-slots.md.
 *
 * Usage: npm run build && node tools/site-slots-doc.mjs
 */
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PORT = 5238;
const BASE_URL = `http://localhost:${PORT}/village-game-web/`;
const DOC = `${ROOT}docs/asset-slots.md`;
const BEGIN = '<!-- SITE-SLOTS:BEGIN (generated by tools/site-slots-doc.mjs, do not edit by hand) -->';
const END = '<!-- SITE-SLOTS:END -->';

function waitForServer(url, timeoutMs = 30000) {
  const start = Date.now();
  return new Promise((resolve, reject) => {
    const tryOnce = () => fetch(url).then(() => resolve()).catch(() => {
      if (Date.now() - start > timeoutMs) reject(new Error('preview server did not start'));
      else setTimeout(tryOnce, 300);
    });
    tryOnce();
  });
}

const compass = ([nx, nz]) => (Math.abs(nx) > Math.abs(nz) ? (nx > 0 ? 'east (+X)' : 'west (-X)') : nz > 0 ? 'south (+Z)' : 'north (-Z)');
const m1 = (v) => (Math.round(v * 10) / 10).toFixed(1);

async function main() {
  const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { cwd: ROOT, stdio: 'pipe' });
  try {
    await waitForServer(BASE_URL);
    const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--disable-gpu-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
    await page.goto(`${BASE_URL}?dev=1`, { waitUntil: 'load' });
    await page.waitForSelector('#start-overlay.ready', { timeout: 30000 }).catch(() => {});
    await page.click('#play-btn');
    await page.waitForTimeout(1500);
    await page.evaluate(() => window.__dopahar.dialogue._advanceFromInput());
    await page.waitForTimeout(2000);
    const data = await page.evaluate(() => {
      const d = window.__dopahar;
      d.zoneManager.update = () => {};
      const sites = [];
      for (const z of d.zoneManager.zones.values()) {
        if (!z.active) {
          const built = z.build();
          const plain = built.isObject3D;
          z.group = plain ? built : built.group;
          z.onFrame = plain ? null : built.onFrame || null;
          d.scene.add(z.group);
          z.active = true;
        }
        const g = z.group;
        if (!g.userData.slotMeta && !g.userData.ownSlot) continue; // lane props, animals, lamps: not places
        if (!d.isPlaceSite(z.name, g.position.x, g.position.z) && !g.userData.ownSlot) continue; // walls, banks, laundry corners, the highway strip
        const info = g.userData.ownSlot ? null : d.siteSlotInfo(g);
        sites.push({ zone: z.name, x: z.x, z: z.z, ownSlot: g.userData.ownSlot || null, info });
      }
      const siteNames = new Set(sites.map((s) => s.zone));
      const hero = d.assetSlotTable().filter((s) => !siteNames.has(s.name)).filter((s) => !/^(tripo_|ceramic_pot$|maa$|dada$|halwai$|postman$|pitaji$|player$|sister$|teacher$|tractor$|trolley$|cart$|bike$|bullock$|charpai$|hand_pump$)/.test(s.name)); // people, vehicles and props have their own tables above
      return { sites, hero, places: d.places.map((p) => ({ id: p.id, en: p.en, hi: p.hi, x: p.x, z: p.z })) };
    });
    await browser.close();

    const placeAt = (x, z) => data.places.find((p) => Math.abs(p.x - x) < 0.01 && Math.abs(p.z - z) < 0.01);
    const lines = [];
    lines.push(BEGIN, '');
    lines.push('### Building slots: every place that streams in', '');
    lines.push('Drop `public/assets/models/<file>.glb` in and reload: the model replaces that place\'s code-built placeholder,');
    lines.push('uniformly scaled to fit the **fit box** below, standing on the ground, centred on the placeholder\'s footprint and');
    lines.push('turned so the model\'s front lands on the **front** below. **In your file the front of the building faces -Z**');
    lines.push('(the same rule as every other slot). The placeholder is only hidden: its walls keep colliding, its bilingual');
    lines.push('signboard stays, and if the file is missing or broken nothing changes. Dimensions are in metres, X = width,');
    lines.push('Y = height, Z = depth of the model as you draw it (front at -Z). **Door** is where the door on the front wall sits,');
    lines.push('measured sideways from the centre of the front wall as seen by someone standing outside (+ = to their right).');
    lines.push('', '| File (`public/assets/models/`) | Place | Stands at (x, z) | Fit box W x H x D | Front faces | Door on the front wall |', '|---|---|---|---|---|---|');
    const rows = data.sites.filter((s) => s.info).sort((a, b) => a.zone.localeCompare(b.zone));
    for (const s of rows) {
      const p = placeAt(s.x, s.z);
      const doors = s.info.doors.length ? s.info.doors.map((d) => `${d.offset >= 0 ? '+' : ''}${m1(d.offset)} m, ${m1(d.w)} x ${m1(d.h)} m`).join('; ') : 'none built (open-fronted or yard)';
      lines.push(`| \`${s.zone}.glb\` | ${p ? `${p.en} / ${p.hi}` : s.zone} | ${s.x}, ${s.z} | ${m1(s.info.w)} x ${m1(s.info.h)} x ${m1(s.info.d)} | ${compass(s.info.front)} | ${doors} |`);
    }
    const own = data.sites.filter((s) => s.ownSlot);
    for (const s of own) {
      const p = placeAt(s.x, s.z);
      lines.push(`| \`${s.zone}.glb\` | ${p ? `${p.en} / ${p.hi}` : s.zone} | ${s.x}, ${s.z} | exact: modelled in the place's own frame (origin = the anchor, 1 unit = 1 m), not fit-scaled | as modelled | as modelled |`);
    }
    lines.push('', 'The anchor of every place (x, z, rotation) lives in one table, `src/anchors.js`; move a place there and its slot follows.', '');
    lines.push('### Building slots: the hero places (registered in `src/main.js`)', '');
    lines.push('| File (`public/assets/models/`) | Fit box W x H x D | Kind |', '|---|---|---|');
    for (const h of data.hero.sort((a, b) => a.name.localeCompare(b.name))) {
      const dim = h.exact ? 'exact: authored in world offsets, not fit-scaled' : h.dimensions ? `${m1(h.dimensions.w)} x ${m1(h.dimensions.h)} x ${m1(h.dimensions.d)}` : '-';
      lines.push(`| \`${h.name}.glb\` | ${dim} | ${h.exact ? 'exact building' : 'fitted'} |`);
    }
    lines.push('', END);
    const block = lines.join('\n');
    let doc = readFileSync(DOC, 'utf8');
    if (doc.includes(BEGIN)) doc = doc.replace(new RegExp(`${BEGIN.replace(/[()*+?.]/g, '\\$&')}[\\s\\S]*?${END}`), block);
    else doc = doc.replace('## Things worth knowing', `${block}\n\n## Things worth knowing`);
    writeFileSync(DOC, doc);
    console.log(`site-slots-doc: ${rows.length} streamed places + ${own.length} exact + ${data.hero.length} hero slots written to docs/asset-slots.md`);
  } finally {
    server.kill();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
